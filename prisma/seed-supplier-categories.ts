async function main() {
  let sortOrder = 0;
  for (const [emoji, name] of CATEGORIES) {
    sortOrder += 1;
    const existing = await prisma.supplierCategory.findUnique({ where: { name } });
    if (existing) {
      console.log(`Skipping "${name}" — already exists.`);
      continue;
    }
    await prisma.supplierCategory.create({ data: { name, emoji, sortOrder } });
    console.log(`Created category: ${emoji} ${name}`);
  }
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
